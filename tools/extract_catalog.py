"""Build js/catalog.js from the Modulhandbuch B.Sc. Informatik (PO 2023).

    python tools/extract_catalog.py docs/Modulhandbuch_BSc_Informatik_PO2023.pdf js/catalog.js

Needs PyMuPDF (pip install pymupdf). Section boundaries are the printed page
numbers from the Modulhandbuch's table of contents; update SECT if a newer
Modulhandbuch moves them.
"""
import json
import re
import sys

import fitz  # PyMuPDF

# printed page where each section starts -> (area id, group key)
SECT = [
    (4, ("A", None)),
    (48, ("B111", None)),
    (59, ("B112", "KI")),
    (98, ("B112", "CYB")),
    (142, ("B112", "KVS")),
    (166, ("B112", "SWHW")),
    (223, ("B112", "THEO")),
    (238, ("B12", "PRAK")),
    (390, ("B12", "SEM")),
    (537, ("B12", "PIL")),
    (608, ("C", None)),
]

CODE_RE = re.compile(r"(\d{2}-[0-9A-Za-z]{2}-)\s*(\d{4}(?:/[a-z]{2})?)")


def section(printed):
    cur = None
    for start, sec in SECT:
        if printed >= start:
            cur = sec
    return cur


def main(src, dst):
    doc = fitz.open(src)
    out = []
    for i, page in enumerate(doc):
        lines = [l.strip() for l in page.get_text("text").splitlines()]
        if "Modulname" not in lines:
            continue
        k = lines.index("Modulname")
        name, j = [], k + 1
        while j < len(lines) and not lines[j].startswith("Modul Nr"):
            if lines[j]:
                name.append(lines[j])
            j += 1
        nm = re.sub(r"^\d+(\.\d+)*\.\s*", "", " ".join(name)).strip()
        nm = re.sub(r"\s*\((eiiss)\)$", "", nm)
        block = " ".join(lines[j : j + 40])
        head = block[: block.find("Sprache")] if "Sprache" in block else block
        c = CODE_RE.search(head)
        cp = re.search(r"(\d+)\s*CP", head)
        lang = None
        m = re.search(r"Sprache\s+(Deutsch und Englisch|Englisch und Deutsch|Deutsch|Englisch)", block)
        if m:
            lang = {"Deutsch": "de", "Englisch": "en"}.get(m.group(1), "de/en")
        area, group = section(i + 1)
        if area in ("A", "C"):
            continue  # fixed modules live in data.js
        out.append(
            {
                "code": (c.group(1) + c.group(2)) if c else "",
                "name": nm,
                "cp": int(cp.group(1)) if cp else 5,
                "a": area,
                "g": group,
                "lang": lang,
            }
        )
    out.sort(key=lambda m: (m["a"], m["g"] or "", m["name"].lower()))
    with open(dst, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/extract_catalog.py from the Modulhandbuch B.Sc. Informatik\n")
        f.write("   (PO 2023, Stand 30.09.2022). Catalogs change every semester - TUCaN is authoritative. */\n")
        f.write("window.CATALOG = ")
        json.dump(out, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    print(f"{len(out)} modules -> {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
